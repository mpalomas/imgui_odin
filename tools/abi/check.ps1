#Requires -Version 7.4
<#
Checks that the Odin bindings have the layout of the C API, on Windows: compiles tools/abi/abi_check.c
against the dear_bindings header (with MSVC, through tools/abi/CMakeLists.txt) and tools/abi/odin against
the bindings, both generated by tools/gen, and compares what they print: the size and alignment of every
struct and typedef, the offset of every field, and the value of every enum element. Linux and macOS use
tools/abi/check.sh.

Usage: tools/abi/check.ps1
Needs the library (tools/build_imgui.ps1 or tools/fetch_imgui_libs.ps1), which the Odin program links.
Environment: ODIN (default: odin from PATH), CMAKE_GENERATOR (see tools/build_imgui.ps1)
#>
$ErrorActionPreference = 'Stop'
$PSNativeCommandUseErrorActionPreference = $true

$Repo = Split-Path -Parent (Split-Path -Parent $PSScriptRoot)
$Odin = $env:ODIN ? $env:ODIN : 'odin'
$Tmp = Join-Path ([System.IO.Path]::GetTempPath()) "imgui_abi_$PID"
New-Item -ItemType Directory -Force $Tmp | Out-Null
try {
    $configure = @('-S', (Join-Path $Repo 'tools/abi'), '-B', "$Tmp/c")
    if ($env:CMAKE_GENERATOR -and $env:CMAKE_GENERATOR -notlike 'Visual Studio*') {
        $configure += '-DCMAKE_BUILD_TYPE=Release'
    }
    cmake @configure | Out-Null
    cmake --build "$Tmp/c" --config Release | Out-Null
    $exe = Get-ChildItem "$Tmp/c" -Recurse -Filter abi_check.exe | Select-Object -First 1
    $c = & $exe.FullName

    $odin = & $Odin run (Join-Path $Repo 'tools/abi/odin') "-out:$Tmp/abi_odin.exe"

    # Line by line, in order.
    $diff = Compare-Object $c $odin -SyncWindow 0 -CaseSensitive | Select-Object -First 20
    if ($diff) {
        $diff | ForEach-Object { "{0} {1}" -f ($_.SideIndicator -eq '<=' ? 'C:   ' : 'Odin:'), $_.InputObject } | Out-Host
        throw 'the Odin bindings do not have the layout of the C API'
    }
    Write-Host "ABI check: $(@($c | Where-Object { $_ }).Count) sizes, offsets and values match"
} finally {
    Remove-Item -Recurse -Force $Tmp -ErrorAction SilentlyContinue
}
